#!/usr/bin/env python3
'''Regenerate bounded public-import indexes for the campaign root.

All Foundations, Paper, and frozen-definition modules, plus exactly the manifest's
SEALED theorem anchors, are publicly re-exported. Drafts and registered providers
are never added to the root. Each index is confined to one area and at most 1200
imports, keeping every generated Lean module below the campaign's 1500-line cap.
'''
from __future__ import annotations

import collections
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
INDEX = ROOT / 'WaveTurbulence' / 'Imports'
MAX_IMPORTS = 1200
MARKER = 'Generated by scripts/update_root_imports.py.'
HEADER = '''/-
Copyright (c) 2026 Scott Armstrong. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong
-/
module

'''
MANAGED = ('WaveTurbulence.Foundations.', 'WaveTurbulence.Paper.',
           'WaveTurbulence.Frozen.Defs.', 'WaveTurbulence.Frozen.Theorems.',
           'WaveTurbulence.Imports.')
IMPORT = re.compile(r'^public import (\S+)$')


def write_if_changed(path: pathlib.Path, text: str) -> None:
    if not path.exists() or path.read_text(encoding='utf-8') != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')


def main() -> None:
    root_text = (ROOT / 'WaveTurbulence.lean').read_text(encoding='utf-8')
    if re.search(r'(?m)^(?:<{7}|={7}|>{7})(?:\s|$)', root_text):
        raise ValueError('Resolve root merge conflict markers before regenerating imports')
    groups: dict[str, set[str]] = collections.defaultdict(set)
    for tree in ('Foundations', 'Paper', 'Frozen/Defs'):
        base = ROOT / 'WaveTurbulence' / tree
        for path in base.rglob('*.lean') if base.exists() else ():
            if path.is_symlink():
                raise ValueError(f'Lean source is a symlink: {path}')
            if tree == 'Frozen/Defs':
                group = 'FrozenDefinitions'
            else:
                relative = path.relative_to(base)
                area = relative.parts[0] if len(relative.parts) > 1 else 'General'
                group = tree + area
            groups[group].add(str(path.relative_to(ROOT).with_suffix('')).replace('/', '.'))
    manifest = json.loads((ROOT / 'manifest/frozen.json').read_text(encoding='utf-8'))
    for anchor in manifest['anchors']:
        if anchor['kind'] == 'theorem' and anchor['state'] == 'SEALED':
            groups['FrozenTheorems'].add(anchor['path'][:-5].replace('/', '.'))

    outputs: dict[pathlib.Path, str] = {}
    for group, modules in sorted(groups.items()):
        modules = sorted(modules)
        parts = [modules[i:i + MAX_IMPORTS] for i in range(0, len(modules), MAX_IMPORTS)]
        for number, part in enumerate(parts, 1):
            name = group if len(parts) == 1 else group + 'Part' + str(number)
            body = '\n'.join('public import ' + module for module in part)
            text = (HEADER + body + '\n\n/-! Public re-exports for ' + group + '.\n'
                    + MARKER + ' -/\npublic section\n')
            if len(text.splitlines()) > 1500:
                raise ValueError(f'Generated index exceeds campaign limit: {name}')
            outputs[INDEX / (name + '.lean')] = text

    for path in INDEX.glob('*.lean') if INDEX.exists() else ():
        if path not in outputs:
            if MARKER not in path.read_text(encoding='utf-8'):
                raise ValueError(f'Refusing to remove a non-generated index: {path}')
            path.unlink()
    for path, text in outputs.items():
        if path.exists() and MARKER not in path.read_text(encoding='utf-8'):
            raise ValueError(f'Refusing to replace a non-generated index: {path}')
        write_if_changed(path, text)

    path = ROOT / 'WaveTurbulence.lean'
    kept = []
    for line in root_text.splitlines():
        match = IMPORT.fullmatch(line)
        if match and match[1].startswith(MANAGED):
            continue
        kept.append(line)
    position = max(i for i, line in enumerate(kept) if IMPORT.fullmatch(line)) + 1
    imports = ['public import ' + str(p.relative_to(ROOT).with_suffix('')).replace('/', '.')
               for p in sorted(outputs)]
    kept[position:position] = imports
    if 'public section' not in kept:
        kept += ['', 'public section']
    text = '\n'.join(kept).rstrip() + '\n'
    if len(text.splitlines()) > 1500:
        raise ValueError('Root module exceeds campaign limit')
    write_if_changed(path, text)
    print(f'Root indexes: {len(outputs)} modules, {sum(map(len, groups.values()))} leaf imports; '
          f'largest index {max(len(t.splitlines()) for t in outputs.values())} lines')


if __name__ == '__main__':
    main()
